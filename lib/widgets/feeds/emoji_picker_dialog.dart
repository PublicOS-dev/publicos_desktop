                              ),
                            ),
                          ),
                        ),
                      ),
                    );
                  },
                )),
              ),

            const SizedBox(height: 4),

            Divider(height: 1, color: tokens.borderSubtle),

            // Emoji grid
            Expanded(
              child: isSearching
                  ? _buildSearchResults(tokens)
                  : _mostUsedEmojis == null
                      ? const SizedBox.shrink()
                      : _buildCategoryGrid(tokens, tabs[tab]),
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildSearchResults(GlassTokens tokens) {
    final results = _searchEmojis(_search);
    if (results.isEmpty) {
      return Center(
        child: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            Icon(
              Icons.search_off_rounded,
              size: 40,
              color: tokens.textDim.withValues(alpha: 0.5),
            ),
            const SizedBox(height: 8),
            Text(
              context.l10n.emojiPickerDialogNoResults,
              style: TextStyle(
                fontFamily: 'SpaceGrotesk',
                color: tokens.textDim,
                fontSize: 13,
              ),
            ),
          ],
        ),
      );
    }

    return GridView.builder(
      padding: const EdgeInsets.all(8),
      gridDelegate: const SliverGridDelegateWithFixedCrossAxisCount(
        crossAxisCount: 8,
        // DESKTOP DELTA: no gap, so the hover hands over from
        // tile to tile with no dead strip (`HoverGrow` fills each tile).
        mainAxisSpacing: 0,
        crossAxisSpacing: 0,
      ),
      itemCount: results.length,
      itemBuilder: (_, i) => _buildEmojiTile(tokens, results[i]),
    );
  }

  Widget _buildCategoryGrid(GlassTokens tokens, _EmojiCategory cat) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        _sectionLabel(tokens, _localizedCategoryName(context, cat.name)),
        Expanded(
          child: GridView.builder(
            controller: _scrollController,
            padding: const EdgeInsets.fromLTRB(8, 0, 8, 8),
            gridDelegate: const SliverGridDelegateWithFixedCrossAxisCount(
              crossAxisCount: 8,
              // DESKTOP DELTA: no gap (see the search grid).
              mainAxisSpacing: 0,
              crossAxisSpacing: 0,
            ),
            itemCount: cat.emojis.length,
            itemBuilder: (_, i) => _buildEmojiTile(tokens, cat.emojis[i]),
          ),
        ),
      ],
    );
  }

  /// The section label: SpaceGrotesk 11 / w800 / spacing 2, dim, uppercase.
  Widget _sectionLabel(GlassTokens tokens, String text) => Padding(
        padding: const EdgeInsets.fromLTRB(12, 10, 12, 4),
        child: Text(
          text.toUpperCase(),
          style: TextStyle(
            fontFamily: 'SpaceGrotesk',
            color: tokens.textDim,
            fontSize: 11,
            fontWeight: FontWeight.w800,
            letterSpacing: 2,
          ),
        ),
      );

  /// Maps a stable category identifier to its localized display name.
  String _localizedCategoryName(BuildContext context, String name) {
    final l10n = context.l10n;
    switch (name) {
      case _mostUsedName:
        return l10n.emojiPickerDialogCategoryMostUsed;
      case 'Smileys':
        return l10n.emojiPickerDialogCategorySmileys;
      case 'People':
        return l10n.emojiPickerDialogCategoryPeople;
      case 'Nature':
        return l10n.emojiPickerDialogCategoryNature;
      case 'Food':
        return l10n.emojiPickerDialogCategoryFood;
      case 'Activities':
        return l10n.emojiPickerDialogCategoryActivities;
      case 'Travel':
        return l10n.emojiPickerDialogCategoryTravel;
      case 'Objects':
        return l10n.emojiPickerDialogCategoryObjects;
      case 'Symbols':
        return l10n.emojiPickerDialogCategorySymbols;
      case 'Flags':
        return l10n.emojiPickerDialogCategoryFlags;
      default:
        return name;
    }
  }

  Widget _buildEmojiTile(GlassTokens tokens, String emoji) {
    final isCurrent = emoji == widget.currentEmoji;

    return Tooltip(
      message: _emojiTags[emoji] ?? emoji,
      waitDuration: const Duration(milliseconds: 400),
      child: InkWell(
        onTap: () => _pick(emoji),
        borderRadius: BorderRadius.circular(8),
        child: Container(
          alignment: Alignment.center,
          decoration: BoxDecoration(
            borderRadius: BorderRadius.circular(8),
            color: isCurrent ? tokens.surfaceElevated : null,
            border: isCurrent
                ? Border.all(color: tokens.borderMedium, width: 1)
                : null,
          ),
          // DESKTOP DELTA: grows 4 px under the pointer.
          child: HoverGrow(
            size: 22,
            child: Text(emoji, style: const TextStyle(fontSize: 22)),
          ),
        ),
      ),
    );
  }
