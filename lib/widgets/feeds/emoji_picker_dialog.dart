// ============================================
// Search index — built once on first use
// ============================================

final List<MapEntry<String, String>> _searchIndex = () {
  // Collect all unique emojis across categories, preserving order
  final seen = <String>{};
  final entries = <MapEntry<String, String>>[];
  for (final cat in _categories) {
    for (final emoji in cat.emojis) {
      if (seen.add(emoji)) {
        final tags = _emojiTags[emoji] ?? '';
        entries.add(MapEntry(emoji, tags));
      }
    }
  }
  return entries;
}();

/// Search emojis by keyword. Each word must match at least one tag.
List<String> _searchEmojis(String query) {
  final words =
      query.toLowerCase().split(RegExp(r'\s+')).where((w) => w.isNotEmpty).toList();
  if (words.isEmpty) return [];

  final results = <String>[];
  for (final entry in _searchIndex) {
    final tags = entry.value;
    bool allMatch = true;
    for (final word in words) {
      if (!tags.contains(word)) {
        allMatch = false;
        break;
      }
    }
    if (allMatch) results.add(entry.key);
  }
  return results;
}

// ============================================
// Usage history — most used first (local, per account)
// ============================================

/// Generic-setting key. The value is a JSON object `{emoji: count}`, bumped on
/// every pick made through this dialog whatever the caller does with it
/// (reaction, list icon, key emoji, wallet icon). Local only, like the chat
/// bookmarks; `PublicOSSettings` scopes it to the active account.
const _historyKey = 'emoji_picker_history';

/// Stable id of the history section (the switch in `_localizedCategoryName`).
const _mostUsedName = 'MostUsed';

/// How many most-used emojis the first section shows: three rows of eight.
const _historyShown = 24;

/// How many distinct emojis the record keeps; the least-used tail falls off.
const _historyStored = 64;

Future<Map<String, int>> _loadHistory() async {
  try {
    final record = await PublicOSSettings.getSetting(_historyKey);
    if (record == null) return <String, int>{};
    final raw = jsonDecode(record.value) as Map<String, dynamic>;
    return raw.map((k, v) => MapEntry(k, (v as num).toInt()));
  } catch (e) {
    print('[EMOJI] history load failed: $e');
    return <String, int>{};
  }
}

/// Count one use. Fire-and-forget from the tile tap; the dialog has already
/// popped by the time this lands.
Future<void> _recordUse(String emoji) async {
  final counts = await _loadHistory();
  counts[emoji] = (counts[emoji] ?? 0) + 1;
  if (counts.length > _historyStored) {
    final kept = _byCount(counts).take(_historyStored).toList();
    counts
      ..clear()
      ..addEntries(kept);
  }
  try {
    await PublicOSSettings.setSetting(
      _historyKey,
      Record.asSettings(
        key: _historyKey,
        value: jsonEncode(counts),
        // A habit, not a cache: it doesn't age out.
        isExpired: false,
        isSystem: true,
      ),
    );
  } catch (e) {
    print('[EMOJI] history save failed: $e');
  }
}

List<MapEntry<String, int>> _byCount(Map<String, int> counts) =>
    counts.entries.toList()..sort((a, b) => b.value.compareTo(a.value));

List<String> _mostUsed(Map<String, int> counts) =>
    _byCount(counts).take(_historyShown).map((e) => e.key).toList();

/// Public door for the reaction quick bar: the top [limit] by use count.
Future<List<String>> mostUsedEmojis({int limit = _historyShown}) async =>
    _byCount(await _loadHistory()).take(limit).map((e) => e.key).toList();

/// Public door for the reaction quick bar: count one use made outside the
/// dialog, so a pill tap tunes the pill like a dialog pick does.
Future<void> recordEmojiUse(String emoji) => _recordUse(emoji);

